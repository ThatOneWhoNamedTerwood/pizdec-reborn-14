using System.Linq;
using System.Numerics;
using Content.Client.Message;
using Content.Client.UserInterface.Controls;
using Content.Shared.PizReb.Gateway;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Shared.GameObjects;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Timing;

namespace Content.Client.PizReb.Gateway;

[GenerateTypedNameReferences]
public sealed partial class ExpeditionGatewayWindow : FancyWindow
{
    [Dependency] private IEntityManager _entMan = default!;
    [Dependency] private IGameTiming _timing = default!;
    [Dependency] private IPrototypeManager _proto = default!;

    public event Action<string>? AcceptPressed;

    private readonly ButtonGroup _cards = new();
    private readonly List<ExpeditionGatewayCard> _entries = new();

    private string? _selected;
    private TimeSpan _nextOffer;
    private TimeSpan _offerInterval = TimeSpan.FromMinutes(5);
    private TimeSpan _readyAt;
    private bool _active;

    public ExpeditionGatewayWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        CooldownLabel.FontColorOverride = Color.FromHex("#d1584f");
        AcceptButton.OnPressed += _ =>
        {
            if (_selected != null)
                AcceptPressed?.Invoke(_selected);
        };
    }

    public void UpdateState(ExpeditionGatewayBoundUserInterfaceState state)
    {
        _active = state.Active;
        _nextOffer = state.NextOffer;
        _offerInterval = state.OfferInterval;
        _readyAt = state.ReadyAt;
        CardsContainer.RemoveAllChildren();
        _entries.Clear();
        foreach (var missionId in state.Missions)
        {
            if (!_proto.TryIndex<GatewayMissionPrototype>(missionId, out var mission))
                continue;
            var rewards = mission.Rewards
                .Select(x => _proto.TryIndex<EntityPrototype>(x, out var reward) ? reward.Name : x.Id);
            var texture = mission.Preview != null ? _entMan.System<SpriteSystem>().Frame0(mission.Preview) : null;
            var card = new ExpeditionGatewayCard(mission.ID, Loc.GetString(mission.Name), texture, string.Join(", ", rewards), _cards);
            card.Selected += () => Select(mission.ID);
            _entries.Add(card);
            CardsContainer.AddChild(card);
        }
        CardsScroll.VScroll = 0;
        CardsScroll.VScrollTarget = 0;
        var keep = _selected != null && _entries.Any(x => x.Name == _selected) ? _selected : _entries.FirstOrDefault()?.Name;
        Select(keep);
    }

    private void Select(string? id)
    {
        if (id == null || !_proto.TryIndex<GatewayMissionPrototype>(id, out var mission))
        {
            _selected = null;
            MissionTitle.Text = string.Empty;
            MissionDifficulty.Text = string.Empty;
            MissionDescription.SetMarkup(string.Empty);
            MissionGoal.SetMarkup(string.Empty);
            MissionReward.SetMarkup(string.Empty);
            MissionImage.Texture = null;
            UpdateAccept();
            return;
        }
        _selected = id;
        foreach (var entry in _entries)
            entry.Pressed = entry.Name == id;
        MissionTitle.Text = Loc.GetString(mission.Name);
        var difficulty = _proto.Index(mission.Difficulty);
        MissionDifficulty.Text = Loc.GetString(difficulty.Name);
        MissionDifficulty.FontColorOverride = difficulty.Color;
        MissionDescription.SetMarkup(mission.Description is { } description ? Loc.GetString(description) : string.Empty);
        MissionGoal.SetMarkup(Loc.GetString(mission.Goal));
        var rewards = mission.Rewards
            .Select(x => _proto.TryIndex<EntityPrototype>(x, out var reward) ? reward.Name : x.Id)
            .Select(x => "- " + x);
        MissionReward.SetMarkup(string.Join("\n", rewards));
        if (mission.Preview != null)
        {
            var texture = _entMan.System<SpriteSystem>().Frame0(mission.Preview);
            MissionImage.Texture = texture;
            MissionImage.TextureScale = Vector2.One * (3.5f / (texture.Size.X / 32f));
        }
        else
        {
            MissionImage.Texture = null;
        }
        UpdateAccept();
    }

    private void UpdateAccept()
    {
        var remaining = _readyAt - _timing.CurTime;
        var cooling = remaining > TimeSpan.Zero;
        CooldownLabel.Visible = cooling;
        if (cooling)
            CooldownLabel.Text = Loc.GetString("gateway-mission-window-cooldown", ("time", $"{remaining.Minutes:00}:{remaining.Seconds:00}"));
        AcceptButton.Disabled = _selected == null || _active || cooling;
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        var remaining = _nextOffer - _timing.CurTime;
        if (remaining <= TimeSpan.Zero)
        {
            NextOfferBar.Value = 1f;
            NextOfferText.Text = "00:00";
        }
        else
        {
            NextOfferBar.Value = 1f - (float)(remaining / _offerInterval);
            NextOfferText.Text = $"{remaining.Minutes:00}:{remaining.Seconds:00}";
        }
        UpdateAccept();
    }
}









