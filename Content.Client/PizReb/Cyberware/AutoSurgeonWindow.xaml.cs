using System.Linq;
using Content.Client.UserInterface.Controls;
using Content.Shared.PizReb.Cyberware;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Enums;
using Robust.Shared.IoC;
using Robust.Shared.Maths;
using Robust.Shared.Network;

namespace Content.Client.PizReb.Cyberware;

[GenerateTypedNameReferences]
public sealed partial class AutoSurgeonWindow : FancyWindow
{
    private readonly Dictionary<Button, NetEntity> _installButtons = new();
    private readonly Dictionary<Button, NetEntity> _replaceButtons = new();
    private readonly IEntityManager _entMan = IoCManager.Resolve<IEntityManager>();
    private NetEntity? _installSelected;
    private NetEntity? _replaceSelected;
    private NetEntity? _replaceTarget;

    public bool AllowClose;

    public event Action<AutoSurgeonMode, NetEntity?, NetEntity?>? StartPressed;

    public AutoSurgeonWindow()
    {
        RobustXamlLoader.Load(this);
        ApplyTheme();
        InstallButton.OnPressed += _ => StartPressed?.Invoke(AutoSurgeonMode.Install, _installSelected, null);
        ReplaceButton.OnPressed += _ => StartPressed?.Invoke(AutoSurgeonMode.Replace, _replaceSelected, _replaceTarget);
        CloseButton.Visible = false;
        StatusButton.OnPressed += _ => SelectTab(0);
        InstallTabButton.OnPressed += _ => SelectTab(1);
        ReplaceTabButton.OnPressed += _ => SelectTab(2);
        SelectTab(0);
    }

    public override void Close()
    {
        if (!AllowClose)
            return;
        base.Close();
    }

    private void ApplyTheme()
    {
        Root.PanelOverride = new StyleBoxFlat
        {
            BackgroundColor = Color.FromHex("#0A0A0C"),
            BorderColor = Color.FromHex("#FF2B4A"),
            BorderThickness = new Thickness(1),
        };

        ContentPanel.PanelOverride = new StyleBoxFlat
        {
            BackgroundColor = Color.FromHex("#101014"),
            BorderColor = Color.FromHex("#FF2B4A"),
            BorderThickness = new Thickness(1),
        };
        ServicePanel.PanelOverride = new StyleBoxFlat
        {
            BackgroundColor = Color.FromHex("#101014"),
            BorderColor = Color.FromHex("#00E5FF"),
            BorderThickness = new Thickness(1),
        };
        ServicePanel.MaxWidth = 210;
        Portrait.OverrideDirection = Direction.South;
        Portrait.WorldRotation = Angle.Zero;
        StatusButton.StyleBoxOverride = MakeButtonStyle(Color.FromHex("#00E5FF"));
        InstallTabButton.StyleBoxOverride = MakeButtonStyle(Color.FromHex("#FF2B4A"));
        ReplaceTabButton.StyleBoxOverride = MakeButtonStyle(Color.FromHex("#FF2B4A"));
        InstallButton.StyleBoxOverride = MakeButtonStyle(Color.FromHex("#FF2B4A"));
        ReplaceButton.StyleBoxOverride = MakeButtonStyle(Color.FromHex("#FF2B4A"));
        PortraitPanel.PanelOverride = new StyleBoxFlat
        {
            BackgroundColor = Color.FromHex("#0C0C10"),
            BorderColor = Color.FromHex("#00E5FF"),
            BorderThickness = new Thickness(1),
        };

        var barBg = new StyleBoxFlat { BackgroundColor = Color.FromHex("#1A1A1F") };
        DurabilityBar.BackgroundStyleBoxOverride = barBg;
        DurabilityBar.ForegroundStyleBoxOverride = new StyleBoxFlat { BackgroundColor = Color.FromHex("#FF2B4A") };
        CapacityBar.BackgroundStyleBoxOverride = barBg;
        CapacityBar.ForegroundStyleBoxOverride = new StyleBoxFlat { BackgroundColor = Color.FromHex("#00E5FF") };
        HeatBar.BackgroundStyleBoxOverride = barBg;
        HeatBar.ForegroundStyleBoxOverride = new StyleBoxFlat { BackgroundColor = Color.FromHex("#FF7A00") };

        InstallButton.Modulate = Color.FromHex("#FFD1D6");
        ReplaceButton.Modulate = Color.FromHex("#FFD1D6");
    }

    private static StyleBoxFlat MakeButtonStyle(Color border)
    {
        return new StyleBoxFlat
        {
            BackgroundColor = Color.FromHex("#141418"),
            BorderColor = border,
            BorderThickness = new Thickness(1),
        };
    }

    private void SelectTab(int tab)
    {
        StatusPanel.Visible = tab == 0;
        InstallPanel.Visible = tab == 1;
        ReplacePanel.Visible = tab == 2;
        StatusButton.Modulate = tab == 0 ? Color.White : Color.FromHex("#00E5FF");
        InstallTabButton.Modulate = tab == 1 ? Color.White : Color.FromHex("#FF8A95");
        ReplaceTabButton.Modulate = tab == 2 ? Color.White : Color.FromHex("#FF8A95");
    }

    public void UpdateState(AutoSurgeonState state)
    {
        PatientLabel.Text = string.IsNullOrEmpty(state.PatientName)
            ? Loc.GetString("cyberware-table-no-patient")
            : state.PatientName;
        DurabilityBar.Value = state.DurabilityValue;
        DurabilityValueLabel.Text = state.Durability;
        CapacityBar.MaxValue = Math.Max(state.Capacity, 1);
        CapacityBar.Value = state.BrainLoad;
        CapacityValueLabel.Text = state.BrainLoad + "/" + state.Capacity;
        HeatBar.Value = state.Heat;
        HeatValueLabel.Text = state.Heat + "%";
        WarningLabel.Text = state.Warning ?? string.Empty;
        WarningLabel.Visible = state.Warning != null;

        InstalledList.DisposeAllChildren();
        foreach (var implant in state.Implants)
            InstalledList.AddChild(MakeImplantLabel(implant));
        StatusEmptyLabel.Visible = state.Implants.Count == 0;
        StatusEmptyLabel.Text = Loc.GetString("cyberware-table-no-implants-patient");
        var tableImplants = state.Contents.Count(x => x.IsImplant);
        InstallEmptyLabel.Visible = tableImplants == 0;
        InstallEmptyLabel.Text = Loc.GetString("cyberware-table-no-implants-table");
        ReplaceEmptyLabel.Visible = tableImplants == 0;
        ReplaceEmptyLabel.Text = Loc.GetString("cyberware-table-no-implants-table");
        ReplaceInstalledEmptyLabel.Visible = state.Implants.Count == 0;
        ReplaceInstalledEmptyLabel.Text = Loc.GetString("cyberware-table-no-implants-patient");

        FillReplaceInstalled(state);
        FillInstallList(state, InstallList, _installButtons, _installSelected, selected =>
        {
            _installSelected = selected;
            InstallButton.Disabled = state.Dressed;
        });
        FillInstallList(state, ReplaceList, _replaceButtons, _replaceSelected, selected =>
        {
            _replaceSelected = selected;
            ReplaceButton.Disabled = state.Dressed;
        });

        ServiceDurabilityLabel.Text = Loc.GetString("cyberware-table-durability", ("value", state.Durability));
        ServiceTankLabel.Text = Loc.GetString("cyberware-table-tank", ("moles", state.TankMoles.ToString("0.0")));
        ServiceJugLabel.Text = Loc.GetString("cyberware-table-jugs", ("count", state.JugCount));
        ServiceStageLabel.Text = state.Operating
            ? Loc.GetString("cyberware-table-stage", ("stage", state.OperationStage))
            : Loc.GetString("cyberware-table-idle");

        InstallButton.Disabled = state.Operating || state.Dressed;
        ReplaceButton.Disabled = state.Operating || state.Dressed;

        if (state.PatientEntity != null)
            Portrait.SetEntity(_entMan.GetEntity(state.PatientEntity.Value));
    }

    private static Label MakeImplantLabel(AutoSurgeonImplantEntry implant)
    {
        return new Label
        {
            Text = implant.Name + " [" + implant.Slot + "] +" + implant.BrainLoad,
            ToolTip = implant.Description,
            Modulate = Color.FromHex("#B8FBFF"),
        };
    }

    private void FillReplaceInstalled(AutoSurgeonState state)
    {
        ReplaceInstalledList.DisposeAllChildren();
        foreach (var implant in state.Implants)
        {
            var target = implant;
            var button = new Button
            {
                Text = target.Name + " [" + target.Slot + "] +" + target.BrainLoad,
                ToolTip = target.Description,
                Modulate = Color.FromHex("#B8FBFF"),
                StyleBoxOverride = MakeButtonStyle(Color.FromHex("#00E5FF")),
            };
            button.OnPressed += _ =>
            {
                _replaceTarget = target.Entity;
                foreach (var other in ReplaceInstalledList.Children)
                {
                    if (other is Button otherButton)
                        otherButton.Modulate = Color.FromHex("#B8FBFF");
                }
                button.Modulate = Color.White;
                ReplaceButton.Disabled = _replaceSelected == null;
            };
            ReplaceInstalledList.AddChild(button);
        }
    }

    private void FillInstallList(AutoSurgeonState state, BoxContainer list, Dictionary<Button, NetEntity> buttons, NetEntity? selected, Action<NetEntity> onSelect)
    {
        list.DisposeAllChildren();
        buttons.Clear();
        foreach (var item in state.Contents)
        {
            if (!item.IsImplant)
                continue;
            var normalColor = Color.FromHex("#B8FBFF");
            var button = new Button
            {
                Text = item.Name + " [" + item.Slot + "] +" + item.BrainLoad,
                Modulate = normalColor,
                StyleBoxOverride = MakeButtonStyle(Color.FromHex("#00E5FF")),
            };
            var net = item.Entity;
            button.OnPressed += _ =>
            {
                foreach (var other in buttons.Keys)
                {
                    other.Pressed = false;
                    other.Modulate = normalColor;
                }
                button.Pressed = true;
                button.Modulate = Color.White;
                onSelect(net);
            };
            if (selected == item.Entity)
            {
                button.Pressed = true;
                button.Modulate = Color.White;
            }
            list.AddChild(button);
            buttons[button] = item.Entity;
        }
    }
}







